-- 1. 전역 설정 테이블 (슬라이더, 메뉴, Cloudinary 설정 등)
CREATE TABLE IF NOT EXISTS public.settings (
  id TEXT PRIMARY KEY,
  hero_images JSONB,
  menu_items JSONB,
  cloudinary_config JSONB,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. 상품 테이블 (골프, 호텔/빌라, 투어 패키지)
CREATE TABLE IF NOT EXISTS public.products (
  id TEXT PRIMARY KEY,
  data JSONB NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. 동영상 갤러리 테이블
CREATE TABLE IF NOT EXISTS public.videos (
  id TEXT PRIMARY KEY,
  data JSONB NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. 커뮤니티 후기/게시판 테이블
CREATE TABLE IF NOT EXISTS public.posts (
  id TEXT PRIMARY KEY,
  data JSONB NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. 개별 페이지 콘텐츠 테이블
CREATE TABLE IF NOT EXISTS public.pages (
  id TEXT PRIMARY KEY,
  data JSONB NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. 공지 팝업 테이블
CREATE TABLE IF NOT EXISTS public.popup (
  id TEXT PRIMARY KEY,
  data JSONB NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. 맞춤 골프여행 패키지 테이블
CREATE TABLE IF NOT EXISTS public.custom_packages (
  id TEXT PRIMARY KEY,
  data JSONB NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. 실시간 고객 상담/채팅 테이블
CREATE TABLE IF NOT EXISTS public.chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL,
  user_name TEXT,
  user_nickname TEXT,
  is_admin BOOLEAN DEFAULT FALSE,
  text TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. 견적 및 예약 문의 테이블
CREATE TABLE IF NOT EXISTS public.inquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data JSONB NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. 회원 관리 테이블 (관리자 및 일반 회원)
CREATE TABLE IF NOT EXISTS public.users (
  id TEXT PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  nickname TEXT,
  role TEXT DEFAULT 'user',
  password_hash TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

